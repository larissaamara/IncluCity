        <h1>Política de Privacidade</h1>

        <h2>1. Apresentação</h2>
        <p>
            A presente Política de Privacidade tem como objetivo informar como o INCLUCITY coleta, utiliza, armazena e
            protege os dados pessoais de seus usuário.
            Ao utiliza a plataforma, o usuário declara estar ciente das práticas descritas neste documento.
        </p>

        <h2>2. Dados Coletados</h2>
        <p>
            O IncluCity pode coletar os seguintes dados:
            <br>2.1 Dados fornecidos pelo usuário:<br>
        </p>
        <ul>
            <li> Nome</li>
            <li>E-mail</li>
            <li>Informações inseridas em avaliações e comentários</li>
        </ul>
        <p>
            2.2 Dados coletados automaticamente:
        </p>
        <ul>
            <li>Endereço IP</li>
            <li>Informações do dispositivo</li>
            <li>Dados de navegação</li>
        </ul>

        <h2>3. Finalidade do uso dos dados</h2>
        <p>
            Os dados coletados são utilizados para:
        </p>
        <ul>
            <li>Permitir o funcionamento da plataforma</li>
            <li>Melhorar a experiência do usuário</li>
            <li>Exibir conteúdos personalizados</li>
            <li>Garantir segurança e prevenção de fraudes</li>
            <li>Gerar estatísticas de uso</li>
        </ul>

        <h2>4. Compatilhamento de dados</h2>
        <p>
            O IncluCity não compartilha dados pessoais com terceiros, exceto:
        </p>
        <ul>
            <li>Quando exigido por lei</li>
            <li>Para cumprimento de obrigações legais</li>
            <li>Para proteção dos direitos da plataforma</li>
        </ul>

        <h2>5. Armazenamento e Segurança</h2>
        <p>
            Os dados são armazenados em ambiente seguro e protegidos contra acesso não autorizado, uso indevido ou
            divulgação.<br>Medidas de segurança incluem:<br>

        </p>
        <ul>
            <li>Controle de acesso</li>
            <li>Criptografia (quando aplicável)</li>
            <li>Monitoramento de atividades</li>
        </ul>

        <h2>6. Direitos do usuário</h2>
        <p>De acordo com a legislação vigente, o usuário pode:</p>
        <ul>
            <li>Solicitar acesso aos seus dados</li>
            <li>Corrigir informações incorretas</li>
            <li>Solicitar exclusão de dados</li>
            <li>Revogar consentimento</li>
        </ul>

        <h2>7. cookies</h2>
        <p>O IncluCity pode utilizar cookies para:</p>
        <ul>
